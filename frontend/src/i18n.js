export function t(key, params = {}) {
  const dict = MESSAGES[locale.value] || MESSAGES.zh
  let str = dict[key] ?? MESSAGES.zh[key] ?? key
  if (params && typeof str === 'string') {
    for (const [k, v] of Object.entries(params)) {
      str = str.replaceAll(`{${k}}`, String(v ?? ''))
    }
  }
  return str
}

export function tData(str) {
  if (!str || locale.value !== 'en') return str
  if (EN_DATA_MAP[str]) return EN_DATA_MAP[str]
  return str
}

export function tFacet(code, fallbackName = '') {
  if (locale.value === 'en') {
    if (code && FACET_CODE_EN[code]) return FACET_CODE_EN[code]
    if (fallbackName && EN_DATA_MAP[fallbackName]) return EN_DATA_MAP[fallbackName]
  }
  return fallbackName || code
}

export function tAlgo(name, fallbackDisplay = '') {
  if (locale.value === 'en' && name && ALGO_NAME_EN[name]) {
    return ALGO_NAME_EN[name]
  }
  return tData(fallbackDisplay || name)
}

export function tAlgoDesc(name, fallbackDesc = '') {
  if (locale.value === 'en' && name && ALGO_DESC_EN[name]) {
    return ALGO_DESC_EN[name]
  }
  return fallbackDesc
}

export function tPath(pathStr) {
  if (!pathStr || locale.value !== 'en') return pathStr
  let out = pathStr.replace(/^\/媒体库\//, '/Library/')
  for (const [zhTerm, enTerm] of Object.entries(EN_DATA_MAP)) {
    if (out.includes(zhTerm)) {
      out = out.replaceAll(zhTerm, enTerm)
    }
  }
  return out
}

